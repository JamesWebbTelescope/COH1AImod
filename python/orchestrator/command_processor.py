class CommandStatus(Enum):
    """Status of a command."""
    PENDING = auto()
    QUEUED = auto()
    EXECUTING = auto()
    COMPLETED = auto()
    FAILED = auto()
    CANCELLED = auto()


class CommandPriority(Enum):
    """Priority levels for commands."""
    URGENT = auto()      # Must be executed immediately (e.g., retreat, emergency repair)
    HIGH = auto()         # High priority (e.g., build critical structure, attack)
    NORMAL = auto()      # Normal priority (default)
    LOW = auto()         # Low priority (e.g., scout, idle unit actions)


@dataclass
class AICommand:
    """Represents an AI command to be executed."""
    command_type: str
    target: Optional[Dict[str, Any]] = None
    parameters: Dict[str, Any] = field(default_factory=dict)
    priority: CommandPriority = CommandPriority.NORMAL
    timestamp: float = field(default_factory=time.time)
    status: CommandStatus = CommandStatus.PENDING
    command_id: str = field(default_factory=lambda: f"cmd_{int(time.time() * 1000)}_{int(time.time() * 1000000) % 1000}")
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert command to dictionary."""
        return {
            "command_id": self.command_id,
            "command_type": self.command_type,
            "target": self.target,
            "parameters": self.parameters,
            "priority": self.priority.name,
            "timestamp": self.timestamp,
            "status": self.status.name
        }
    
    def to_json(self) -> str:
        """Convert command to JSON string."""
        return json.dumps(self.to_dict(), ensure_ascii=False)


@dataclass
class CommandProcessorStats:
    """Statistics for the command processor."""
    commands_received: int = 0
    commands_processed: int = 0
    commands_executed: int = 0
    commands_failed: int = 0
    commands_cancelled: int = 0
    queue_length: int = 0
    average_execution_time: float = 0.0
    last_command_time: float = 0.0
    last_error_time: float = 0.0
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert stats to dictionary."""
        return {
            "commands_received": self.commands_received,
            "commands_processed": self.commands_processed,
            "commands_executed": self.commands_executed,
            "commands_failed": self.commands_failed,
            "commands_cancelled": self.commands_cancelled,
            "queue_length": self.queue_length,
            "average_execution_time": self.average_execution_time,
            "last_command_time": self.last_command_time,
            "last_error_time": self.last_error_time
        }


class CommandProcessor:
    """
    Processes and executes AI commands.
    
    Manages the command queue, validates commands, and tracks their execution.
    """
    
    def __init__(self, config: Configuration = None, ipc_reader=None):
        """
        Initialize command processor.
        
        Args:
            config: Configuration instance
            ipc_reader: IPC reader instance for sending commands
        """
        self.config = config or Configuration()
        self.ipc_reader = ipc_reader
        self.logger = logging.getLogger(__name__)
        
        # Command queue and history
        self.command_queue = deque()
        self.command_history = deque(maxlen=1000)
        self._lock = threading.Lock()
        
        # Statistics
        self.stats = CommandProcessorStats()
        
        # Configuration
        self.max_queue_length = self.config.get("command_processor", "max_queue_length", default=50)
        self.max_retries = self.config.get("command_processor", "max_retries", default=3)
        self.execution_timeout = self.config.get("command_processor", "execution_timeout", default=10.0)
        
        # State
        self.running = False
        self.thread = None
        
        self.logger.info("Command processor initialized")
    
    def start(self) -> bool:
        """Start the command processor."""
        if self.running:
            self.logger.warning("Command processor is already running")
            return False
        
        self.running = True
        self.logger.info("Command processor started")
        return True
    
    def stop(self) -> bool:
        """Stop the command processor."""
        if not self.running:
            return True
        
        self.running = False
        
        # Wait for thread to finish if it exists
        if self.thread and self.thread.is_alive():
            self.thread.join(timeout=1.0)
        
        self.logger.info("Command processor stopped")
        return True
    
    def add_command(self, command: AICommand) -> bool:
        """
        Add a command to the queue.
        
        Args:
            command: AICommand to add
            
        Returns:
            True if command was added successfully, False otherwise
        """
        if not self.running:
            self.logger.warning("Command processor is not running, cannot add command")
            return False
        
        try:
            with self._lock:
                # Validate command
                if not self._validate_command(command):
                    self.stats.last_error_time = time.time()
                    return False
                
                # Check queue length
                if len(self.command_queue) >= self.max_queue_length:
                    self.logger.warning(f"Command queue full ({len(self.command_queue)} commands), cannot add new command")
                    return False
                
                # Set command status to QUEUED
                command.status = CommandStatus.QUEUED
                
                # Add command to queue based on priority
                self._add_command_to_queue(command)
                
                # Update statistics
                self.stats.commands_received += 1
                self.stats.queue_length = len(self.command_queue)
                self.stats.last_command_time = time.time()
                
                self.logger.debug(f"Added command {command.command_id}: {command.command_type}")
                return True
                
        except Exception as e:
            self.logger.error(f"Error adding command: {e}")
            return False
    
    def add_commands(self, commands: List[AICommand]) -> int:
        """
        Add multiple commands to the queue.
        
        Args:
            commands: List of AICommand to add
            
        Returns:
            Number of commands successfully added
        """
        count = 0
        for command in commands:
            if self.add_command(command):
                count += 1
        return count
    
    def _add_command_to_queue(self, command: AICommand):
        """
        Add command to queue based on priority.
        
        Args:
            command: Command to add
        """
        # Convert priority to sortable integer
        priority_order = {
            CommandPriority.URGENT: 0,
            CommandPriority.HIGH: 1,
            CommandPriority.NORMAL: 2,
            CommandPriority.LOW: 3
        }
        
        # Find position to insert
        inserted = False
        for i, existing in enumerate(self.command_queue):
            if priority_order.get(command.priority, 2) < priority_order.get(existing.priority, 2):
                self.command_queue.insert(i, command)
                inserted = True
                break
        
        if not inserted:
            self.command_queue.append(command)
    
    def process_queue(self) -> int:
        """
        Process the command queue.
        
        Returns:
            Number of commands processed
        """
        if not self.running:
            self.logger.warning("Command processor is not running, cannot process queue")
            return 0
        
        processed_count = 0
        
        try:
            with self._lock:
                while self.command_queue and self.running:
                    command = self.command_queue.popleft()
                    
                    # Process command
                    success = self._process_command(command)
                    
                    if success:
                        processed_count += 1
                    
                    # Update queue length stat
                    self.stats.queue_length = len(self.command_queue)
                    
                    # Limit batch processing
                    if processed_count >= 10:  # Process max 10 commands at a time
                        break
                        
        except Exception as e:
            self.logger.error(f"Error processing command queue: {e}")
        
        return processed_count
    
    def _process_command(self, command: AICommand) -> bool:
        """
        Process a single command.
        
        Args:
            command: Command to process
            
        Returns:
            True if processed successfully, False otherwise
        """
        start_time = time.time()
        
        try:
            # Update command status
            command.status = CommandStatus.EXECUTING
            
            # Execute command
            success = self._execute_command(command)
            
            if success:
                command.status = CommandStatus.COMPLETED
                self.stats.commands_executed += 1
                self.logger.debug(f"Command {command.command_id} executed successfully")
            else:
                command.status = CommandStatus.FAILED
                self.stats.commands_failed += 1
                self.logger.warning(f"Command {command.command_id} failed")
            
            # Add to history
            self.command_history.append(command)
            
            # Update statistics
            self.stats.commands_processed += 1
            execution_time = time.time() - start_time
            
            if self.stats.commands_processed > 0:
                self.stats.average_execution_time = (
                    (self.stats.average_execution_time * (self.stats.commands_processed - 1)) + execution_time
                ) / self.stats.commands_processed
            else:
                self.stats.average_execution_time = execution_time
            
            return success
            
        except Exception as e:
            command.status = CommandStatus.FAILED
            self.stats.commands_failed += 1
            self.logger.error(f"Error processing command {command.command_id}: {e}")
            return False
    
    def _execute_command(self, command: AICommand) -> bool:
        """
        Execute a single command.
        
        Args:
            command: Command to execute
            
        Returns:
            True if executed successfully, False otherwise
        """
        # Convert command to dictionary for sending
        command_dict = command.to_dict()
        
        # Remove internal fields that SCAR doesn't need
        command_dict.pop('command_id', None)
        command_dict.pop('status', None)
        command_dict.pop('timestamp', None)
        command_dict.pop('priority', None)
        
        # Send command via IPC
        if self.ipc_reader:
            return self.ipc_reader.send_command(command_dict)
        else:
            # No IPC reader, just log the command
            self.logger.info(f"Command to execute: {command.command_type}")
            return True
    
    def _validate_command(self, command: AICommand) -> bool:
        """
        Validate a command.
        
        Args:
            command: Command to validate
            
        Returns:
            True if valid, False otherwise
        """
        if not isinstance(command, AICommand):
            self.logger.error("Command is not an AICommand instance")
            return False
        
        if not command.command_type:
            self.logger.error("Command has no command_type")
            return False
        
        # Check command type is a string
        if not isinstance(command.command_type, str):
            self.logger.error(f"Command type must be string, got {type(command.command_type)}")
            return False
        
        # Validate priority
        if not isinstance(command.priority, CommandPriority):
            self.logger.error(f"Invalid priority type: {type(command.priority)}")
            return False
        
        return True
    
    def get_next_command(self) -> Optional[AICommand]:
        """
        Get the next command from the queue without removing it.
        
        Returns:
            Next command or None if queue is empty
        """
        with self._lock:
            if self.command_queue:
                return self.command_queue[0]
            return None
    
    def get_queue(self) -> List[Dict[str, Any]]:
        """
        Get the entire command queue.
        
        Returns:
            List of command dictionaries
        """
        with self._lock:
            return [cmd.to_dict() for cmd in self.command_queue]
    
    def get_queue_length(self) -> int:
        """
        Get the current queue length.
        
        Returns:
            Number of commands in queue
        """
        with self._lock:
            return len(self.command_queue)
    
    def get_history(self, count: int = 100) -> List[Dict[str, Any]]:
        """
        Get command history.
        
        Args:
            count: Number of historical commands to return
            
        Returns:
            List of command dictionaries
        """
        with self._lock:
            start = max(0, len(self.command_history) - count)
            return [cmd.to_dict() for cmd in list(self.command_history)[start:]]
    
    def clear_queue(self) -> int:
        """
        Clear the command queue.
        
        Returns:
            Number of commands cleared
        """
        with self._lock:
            count = len(self.command_queue)
            self.command_queue.clear()
            self.stats.queue_length = 0
            return count
    
    def cancel_command(self, command_id: str) -> bool:
        """
        Cancel a command in the queue.
        
        Args:
            command_id: ID of command to cancel
            
        Returns:
            True if command was found and cancelled, False otherwise
        """
        with self._lock:
            for command in self.command_queue:
                if command.command_id == command_id:
                    command.status = CommandStatus.CANCELLED
                    self.stats.commands_cancelled += 1
                    self.logger.info(f"Cancelled command {command_id}")
                    return True
            return False
    
    def get_command_by_id(self, command_id: str) -> Optional[Dict[str, Any]]:
        """
        Get a command by its ID.
        
        Args:
            command_id: ID of command to find
            
        Returns:
            Command dictionary or None if not found
        """
        with self._lock:
            # Search queue
            for command in self.command_queue:
                if command.command_id == command_id:
                    return command.to_dict()
            
            # Search history
            for command in self.command_history:
                if command.command_id == command_id:
                    return command.to_dict()
            
            return None
    
    def get_stats(self) -> CommandProcessorStats:
        """Get current statistics."""
        return self.stats
    
    def reset_stats(self):
        """Reset statistics."""
        self.stats = CommandProcessorStats()


